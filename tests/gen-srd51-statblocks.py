import re, json
t = open('/workspace/hearth-160/app/index.html').read()
start = t.index('const MONSTERS = [')
seg = t[start:start+400000]
ents = re.findall(r"\{ id: '(m_[a-z0-9_]*)', name: '((?:[^'\\]|\\.)*)', cr: ([\d./]+), size: '(\w+)', type: '[^']*', ac: (\d+), hp: (\d+)", seg)
srd = {x['name']: x for x in json.load(open('/workspace/o5e/mon_srd.json')) if x.get('document__slug') == 'wotc-srd'}
alias = {'Cultist Fanatic': 'Cult Fanatic'}
out, skipped = {}, []
def clean(s): return re.sub(r'\s+', ' ', (s or '')).strip()
for mid, name, cr, size, ac, hp in ents:
    nm = name.replace("\\'", "'")
    s = srd.get(alias.get(nm, nm))
    if not s: skipped.append((nm, 'not in SRD 5.1')); continue
    if int(ac) != s['armor_class'] or int(hp) != s['hit_points']:
        skipped.append((nm, f"AC/HP differ app {ac}/{hp} vs SRD {s['armor_class']}/{s['hit_points']}")); continue
    saves = {k: s[f'{full}_save'] for k, full in [('str','strength'),('dex','dexterity'),('con','constitution'),('int','intelligence'),('wis','wisdom'),('cha','charisma')] if s.get(f'{full}_save') is not None}
    ent = {
        'name': s['name'], 'alignment': s.get('alignment') or '', 'acDesc': s.get('armor_desc') or '',
        'saves': saves, 'skills': s.get('skills') or {},
        'vuln': s.get('damage_vulnerabilities') or '', 'res': s.get('damage_resistances') or '',
        'imm': s.get('damage_immunities') or '', 'condImm': s.get('condition_immunities') or '',
        'senses': s.get('senses') or '', 'languages': s.get('languages') or '',
        'traits': [{'name': a['name'], 'desc': clean(a['desc'])} for a in (s.get('special_abilities') or [])],
        'actions': [{'name': a['name'], 'desc': clean(a['desc'])} for a in (s.get('actions') or [])],
        'bonus': [{'name': a['name'], 'desc': clean(a['desc'])} for a in (s.get('bonus_actions') or [])],
        'reactions': [{'name': a['name'], 'desc': clean(a['desc'])} for a in (s.get('reactions') or [])],
        'legDesc': clean(s.get('legendary_desc')),
        'legendary': [{'name': a['name'], 'desc': clean(a['desc'])} for a in (s.get('legendary_actions') or [])],
    }
    ent = {k: v for k, v in ent.items() if v not in ('', [], {})}
    out[mid] = ent
js = ("/* Hearth DM screen (C2): full stat blocks for the catalogue monsters.\n"
      " * Text from the System Reference Document 5.1 (SRD 5.1) by Wizards of the Coast LLC,\n"
      " * https://dnd.wizards.com/resources/systems-reference-document , licensed under the\n"
      " * Creative Commons Attribution 4.0 International License (CC-BY-4.0),\n"
      " * https://creativecommons.org/licenses/by/4.0/legalcode . Changes: reformatted into\n"
      " * Hearth's data shape. Generated by tests/gen-srd51-statblocks.py from Open5e's SRD export.\n */\n"
      "window.HEARTH_SRD51_BLOCKS = " + json.dumps(out, ensure_ascii=False, separators=(',', ':')) + ";\n")
open('/workspace/hearth-160/app/dm/srd51-statblocks.js', 'w').write(js)
print(len(ents), 'catalogue;', len(out), 'blocks;', len(js)//1024, 'KB')
for s in skipped: print('skip', s)
